self.addEventListener('install', event => {
  // a new version WAITS (never replaces the app mid-reading): it applies on the next open or when «Обновить» is pressed
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const base = self.registration.scope;
    await cache.addAll(ASSETS.map(p => new Request(new URL(p, base).href, { cache: 'reload' })));
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('konspekty-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => { if (event.data === 'skipWaiting') self.skipWaiting(); });

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;   // внешних запросов приложение не делает
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (req.mode === 'navigate') {
      const cached = await cache.match(new URL('index.html', self.registration.scope).href);
      if (cached) return cached;
    }
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      // only complete responses are cached (never a 206 partial or an opaque/redirected one)
      if (res.status === 200 && res.type === 'basic' && !res.headers.has('content-range')) cache.put(req, res.clone()).catch(() => {});
      return res;
    } catch {
      return new Response('Нет соединения', { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
    }
  })());
});
