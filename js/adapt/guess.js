// Subject guess by keywords (title weighs more than the body).
const KW = {
  anatomy: ['анатом', 'ангиолог', 'артери', 'вена', 'вены', 'кость', 'кости', 'сустав', 'мышц', 'сосуд', 'мочеполов', 'висцерол', 'остеолог', 'миолог', 'спланхнолог'],
  patanatomy: ['патанатом', 'патологическ', 'некроз', 'воспален', 'опухол', 'дистроф', 'атрофия', 'склероз', 'тромбоз', 'инфаркт'],
  biochem: ['биохим', 'фермент', 'белок', 'белки', 'обмен', 'глюкоз', 'липид', 'аминокислот', 'гликолиз', 'метаболизм', 'витамин'],
  histology: ['гистолог', 'эпители', 'препарат', 'окраска', 'цитолог', 'эмбриолог', 'ткани'],
  microbio: ['микробиолог', 'бактери', 'вирус', 'антибиотик', 'генетика бактер', 'иммунитет', 'стафилококк', 'культур'],
  dentistry: ['стоматолог', 'зуб', 'ортопед', 'пародонт', 'кариес', 'протез', 'челюст', 'прикус', 'пульпит'],
  philosophy: ['философ', 'онтолог', 'гносеолог', 'бытие', 'сознание', 'диалектик', 'кант', 'платон', 'аристотель', 'этика'],
  physiology: ['физиолог', 'потенциал', 'рефлекс', 'гомеостаз', 'дыхани', 'возбуждени', 'мембран', 'гормон', 'синапс'],
};
export function guessSubject(title, text) {
  const t = (title || '').toLowerCase(), b = (text || '').slice(0, 6000).toLowerCase();
  const score = {}; let total = 0;
  for (const [k, words] of Object.entries(KW)) { let s = 0; for (const w of words) { if (t.includes(w)) s += 8; s += Math.min(6, (b.split(w).length - 1)); } score[k] = s; total += s; }
  const best = Object.entries(score).sort((a, b2) => b2[1] - a[1]);
  const [key, s] = best[0];
  return { key: s >= 6 ? key : null, confidence: total ? s / total : 0, score };
}
