// Photo -> theme: dominant colours (k-means in pure JS) -> full token set -> WCAG check -> styles/themes/<name>.css
//   node tools/palette.mjs photo.jpg --name sea [--dark] [--write]
// Without --write the CSS is only printed. The text colours are darkened/lightened until they pass 4.5:1 on their panels.
import fs from 'node:fs';
import { loadSharp, arg, hex, rgb2hsl, hsl2rgb, contrast } from './lib-image.mjs';

const input = process.argv[2];
if (!input || input.startsWith('--')) { console.error('Usage: node tools/palette.mjs photo.jpg --name sea [--dark] [--write]'); process.exit(1); }
const sharp = await loadSharp();
const name = String(arg('name', 'custom')).toLowerCase().replace(/[^\w-]+/g, '-');
const dark = !!arg('dark', false);

// k-means on a 64x64 thumbnail
const { data } = await sharp(input).rotate().resize(64, 64, { fit: 'cover' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const pts = []; for (let i = 0; i < data.length; i += 3) pts.push([data[i], data[i + 1], data[i + 2]]);
function kmeans(points, k, iters = 18) {
  let cent = Array.from({ length: k }, (_, i) => points[Math.floor((i + .5) * points.length / k)].slice());
  let groups = [];
  for (let it = 0; it < iters; it++) {
    groups = Array.from({ length: k }, () => []);
    for (const p of points) { let b = 0, bd = 1e9; cent.forEach((c, i) => { const d = (p[0] - c[0]) ** 2 + (p[1] - c[1]) ** 2 + (p[2] - c[2]) ** 2; if (d < bd) { bd = d; b = i; } }); groups[b].push(p); }
    cent = cent.map((c, i) => groups[i].length ? [0, 1, 2].map(j => groups[i].reduce((a, p) => a + p[j], 0) / groups[i].length) : c);
  }
  return cent.map((c, i) => ({ c, n: groups[i].length })).sort((a, b) => b.n - a.n);
}
const dom = kmeans(pts, 6);
console.log('dominant colours:', dom.map(d => hex(d.c) + ` (${Math.round(d.n / pts.length * 100)}%)`).join('  '));

// pick hues
const hsl = dom.map(d => ({ ...d, hsl: rgb2hsl(d.c) }));
const main = hsl.slice().sort((a, b) => b.hsl[1] * Math.min(b.n, 200) - a.hsl[1] * Math.min(a.n, 200))[0];   // saturated and present
const [H, S] = main.hsl;
const sat = Math.min(0.55, Math.max(0.18, S));
const L = (h, s, l) => hex(hsl2rgb([h, s, l]));

// text colours with guaranteed contrast
function ensure(fg, bg, min, towards) {
  let c = fg.slice(), guard = 0;
  while (contrast(c, bg) < min && guard++ < 80) c = towards === 'dark' ? c.map(v => v * 0.94) : c.map(v => v + (255 - v) * 0.08);
  return c;
}
const t = {};
if (!dark) {
  const panel = [255, 255, 255];
  t.bg = L(H, 0.2, 0.955); t.panel = '#ffffff'; t.panel2 = L(H, 0.25, 0.975); t.line = 'rgba(43, 28, 58, .08)';
  const ink = ensure(hsl2rgb([H, 0.18, 0.14]), panel, 12, 'dark'); t.ink = hex(ink);
  t.ink2 = hex(ensure(hsl2rgb([H, 0.12, 0.38]), panel, 5, 'dark')); t.ink3 = hex(ensure(hsl2rgb([H, 0.1, 0.5]), panel, 4.5, 'dark'));
  t.accent = L(H, Math.min(.7, sat + .15), 0.78); t.accentSoft = L(H, 0.55, 0.95);
  t.accentInk = hex(ensure(hsl2rgb([H, Math.min(.65, sat + .2), 0.4]), panel, 4.5, 'dark'));
  t.onAccent = t.ink;
} else {
  const panel = [24, 38, 82];
  t.bg = L(H, 0.5, 0.12); t.panel = 'rgba(255, 255, 255, .06)'; t.panel2 = 'rgba(255, 255, 255, .09)'; t.line = 'rgba(255, 255, 255, .1)';
  t.ink = hex(ensure(hsl2rgb([H, 0.6, 0.95]), panel, 10, 'light')); t.ink2 = hex(ensure(hsl2rgb([H, 0.35, 0.78]), panel, 6, 'light')); t.ink3 = hex(ensure(hsl2rgb([H, 0.25, 0.65]), panel, 4.5, 'light'));
  t.accent = L(H, Math.min(.7, sat + .2), 0.66); t.accentSoft = `rgba(${hsl2rgb([H, .6, .66]).map(Math.round).join(', ')}, .2)`;
  t.accentInk = hex(ensure(hsl2rgb([H, .6, .78]), panel, 4.5, 'light')); t.onAccent = '#0b1430';
}
// highlighter colours: six pastel hues around the wheel, seeded by the photo's main hue
const marks = [50, 340, 130, 205, 270, 25].map(h => L(h, 0.9, 0.84));

const check = (a, b) => Math.round(contrast(a, b) * 10) / 10;
const ph = v => v.startsWith('#') ? v : '#ffffff';
const report = dark ? [] : [
  ['ink on panel', check(parseHexSafe(t.ink), [255, 255, 255])],
  ['accent text on white', check(parseHexSafe(t.accentInk), [255, 255, 255])],
];
function parseHexSafe(h) { h = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); }
console.log('contrast report:', JSON.stringify(report));
void ph;

const css = `/* Theme «${name}» — generated by tools/palette.mjs from ${input.split('/').pop()} */
[data-theme="${name}"] {
  color-scheme: ${dark ? 'dark' : 'light'};
  --bg: ${t.bg};
  --bg-grad: radial-gradient(60% 50% at 12% 8%, ${L(H, .5, dark ? .2 : .93)}, transparent 70%), linear-gradient(180deg, ${t.bg}, ${L(H, .25, dark ? .09 : .93)});
  --veil: transparent;
  --panel: ${t.panel}; --panel-2: ${t.panel2}; --line: ${t.line};
  --ink: ${t.ink}; --ink2: ${t.ink2}; --ink3: ${t.ink3};
  --accent: ${t.accent}; --accent-2: ${L(H, .5, .88)}; --accent-soft: ${t.accentSoft}; --accent-ink: ${t.accentInk};
  --ice: ${t.accent}; --ice-soft: ${t.accentSoft}; --mint: #5fb5a2;
  --on-accent: ${t.onAccent};
  --btn-grad: linear-gradient(180deg, ${L(H, .6, dark ? .72 : .84)}, ${t.accent});
  --btn-shadow: 0 8px 18px -10px ${t.accent};
  --danger: ${dark ? '#ff8aa5' : '#c4284f'}; --danger-soft: ${dark ? 'rgba(255, 138, 165, .15)' : '#fdecef'}; --ok: ${dark ? '#6fd0bb' : '#2f8a74'};
  --glass: ${dark ? 'rgba(24, 38, 82, .72)' : 'rgba(250, 249, 252, .78)'}; --glass-edge: ${dark ? 'rgba(255, 255, 255, .12)' : 'rgba(43, 28, 58, .09)'};
  --side-bg: ${dark ? 'rgba(255, 255, 255, .05)' : 'rgba(250, 249, 252, .82)'};
  --shadow: 0 1px 2px rgba(43, 28, 58, .05), 0 18px 40px -26px rgba(72, 44, 96, .32);
  --shadow-pop: 0 10px 28px -12px rgba(72, 44, 96, .38);
  --hero-grad: linear-gradient(168deg, ${L(H, .5, dark ? .22 : .94)}, ${L(H, .35, dark ? .16 : .97)});
  --desk: ${L(H, .15, dark ? .08 : .92)};
  --seg-bg: ${dark ? 'rgba(255, 255, 255, .08)' : 'rgba(43, 28, 58, .06)'};
  --scrim: ${dark ? 'rgba(3, 8, 24, .55)' : 'rgba(38, 33, 43, .32)'};
  /* subject tints: keep from the default theme or override here */
}
/* optional: retune the highlighter colours for this theme (documents stay on light paper) */
/* [data-theme="${name}"] { --mark-1: ${marks[0]}; --mark-2: ${marks[1]}; --mark-3: ${marks[2]}; --mark-4: ${marks[3]}; --mark-5: ${marks[4]}; --mark-6: ${marks[5]}; } */
`;
if (arg('write', false)) {
  fs.writeFileSync(`styles/themes/${name}.css`, css);
  console.log(`written styles/themes/${name}.css — add it to index.html, to THEMES in config.js and to THEME_COLOR in js/theme.js`);
} else console.log('\n' + css);
