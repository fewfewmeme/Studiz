// Updates the version (js/version.js) and the file list + cache version in sw.js. Run: node tools/build-sw.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const include = ['index.html', 'manifest.webmanifest', 'config.js', 'robots.txt'];
const dirs = ['js', 'styles', 'vendor', 'icons', 'assets'];
const skip = /(^|\/)(README\.md|\.DS_Store)$|^assets\/originals\//;

function walk(dir, out) {
  for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = dir + '/' + e.name;
    if (e.isDirectory()) walk(rel, out);
    else if (!skip.test(rel)) out.push(rel);
  }
}
const files = [...include];
for (const d of dirs) if (fs.existsSync(path.join(root, d))) walk(d, files);
files.sort();
const hash = crypto.createHash('sha256');
for (const f of files) { if (f === 'js/version.js') continue; hash.update(f); hash.update(fs.readFileSync(path.join(root, f))); }
const version = hash.digest('hex').slice(0, 10);

fs.writeFileSync(path.join(root, 'js/version.js'), `// generated by tools/build-sw.mjs\nexport const APP_VERSION = '${version}';\n`);
let sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
sw = sw.replace(/const VERSION = '[^']*';/, `const VERSION = '${version}';`);
sw = sw.replace(/\/\/ BEGIN ASSETS[\s\S]*\/\/ END ASSETS/, `// BEGIN ASSETS\nconst ASSETS = [\n  './',\n${files.map(f => `  '${f}',`).join('\n')}\n];\n// END ASSETS`);
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: version ${version}, cached files: ${files.length}`);
